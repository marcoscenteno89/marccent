// Generates app/styles/grid.css — a CSS Grid layout system (no Bootstrap).
// Edit the config below, then run: npm run grid
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const COLUMNS = 12;

// Mobile-first breakpoints (min-width). Base classes (no infix) apply below `xs`.
const BREAKPOINTS = {
  xs: 375,  // standard phones (below this: small phones, ~320–374px)
  sm: 576,  // large phones / phones in landscape
  md: 768,  // tablets portrait
  lg: 1024, // tablets landscape / small laptops
  xl: 1280, // desktops
  xxl: 1536 // wide screens
};

// Max .wrap width at each breakpoint (fluid below `sm`).
const WRAP = { sm: 540, md: 720, lg: 960, xl: 1200, xxl: 1440 };

// Gap scale, same as Bootstrap's spacers, so g-3 -> gap-3 is a 1:1 swap.
const GAPS = { 0: '0', 1: '.25rem', 2: '.5rem', 3: '1rem', 4: '1.5rem', 5: '3rem' };

// Items-per-row presets for .per-* (must divide COLUMNS).
const PER_ROW = [1, 2, 3, 4, 6, 12];

const bps = Object.entries(BREAKPOINTS);
const infix = bp => (bp ? `-${bp}` : '');

function responsive(bp) {
  const i = infix(bp);
  const out = [];

  for (const n of PER_ROW) out.push(`.per${i}-${n} { --grid-span: ${COLUMNS / n}; }`);

  for (let n = 1; n <= COLUMNS; n++) out.push(`.span${i}-${n} { grid-column-end: span ${n}; }`);
  out.push(`.span${i}-full { grid-column: 1 / -1; }`);

  // Column line to start on (1-based), e.g. .start-md-9 begins in column 9.
  out.push(`.start${i}-auto { grid-column-start: auto; }`);
  for (let n = 1; n <= COLUMNS; n++) out.push(`.start${i}-${n} { grid-column-start: ${n}; }`);

  // Same names and values as Bootstrap's order utilities, so the two never disagree.
  out.push(`.order${i}-first { order: -1; }`);
  out.push(`.order${i}-last { order: 6; }`);
  for (let n = 0; n <= 5; n++) out.push(`.order${i}-${n} { order: ${n}; }`);

  for (const [k, v] of Object.entries(GAPS)) out.push(`.gap${i}-${k} { gap: ${v}; }`);

  // Stacked (single column) until this breakpoint, then children sit in one row.
  if (bp) {
    out.push(`.flow${i} { grid-auto-flow: column; grid-auto-columns: minmax(0, 1fr); }`);
    out.push(`.flow${i}.flow-fit { grid-auto-columns: auto; }`);
    out.push(`.hide${i}-up { display: none !important; }`);
  }

  return out;
}

function wraps(bp) {
  if (!(bp in WRAP)) return [];
  // .wrap-{x} is capped from breakpoint x upward.
  const idx = bps.findIndex(([k]) => k === bp);
  const names = ['.wrap', ...bps.slice(0, idx + 1).map(([k]) => `.wrap-${k}`)];
  return [`${names.join(',\n')} { max-width: ${WRAP[bp]}px; }`];
}

const indent = lines => lines.map(l => l.replace(/^/gm, '  ')).join('\n');

const css = [];
css.push(`/*
 * CSS Grid layout system. GENERATED by scripts/grid.mjs; edit that, not this.
 *
 * Breakpoints (mobile-first, min-width):
 *   (none) <${BREAKPOINTS.xs}px  ${bps.map(([k, v]) => `${k} ${v}px`).join('  ')}
 *
 * Wrappers     .wrap                    centered, max-width per breakpoint
 *              .wrap-{bp}               100% wide until {bp}, then capped
 *              .wrap-fluid              always 100%
 *
 * 12-col grid  .grid                    children default to full width (stack on mobile)
 *              .span[-bp]-{1..12|full}  span N columns
 *              .start[-bp]-{1..12|auto} start in column N
 *              .per[-bp]-{${PER_ROW.join('|')}}  on the PARENT: N items per row, no child classes needed
 *              .order[-bp]-{first|last|0..5}
 *
 * Flow         .flow                    equal-width columns, one per child (like .row > .col)
 *              .flow-{bp}               stacked until {bp}, then a row
 *              .flow-fit                columns sized to content (like .col-auto)
 *
 * Auto-fit     .grid-fit                as many columns as fit, each >= --grid-min (default 16rem)
 *
 * Gaps         .gap[-bp]-{0..5}  .gap-x-{0..5}  .gap-y-{0..5}   (also work on flex containers)
 * Alignment    .items-{start|center|end|stretch}  .justify-{...}  .self-{...}  .justify-self-{...}
 *              .content-{start|center|end|between}
 * Visibility   .hide-{bp}-up  /  .hide-{bp}-down  (no need to restate display)
 */`);

css.push(`:root {
  --grid-gutter: 1rem;
  --grid-pad: 1rem;
  --grid-min: 16rem;
}`);

css.push(`.wrap,
${bps.map(([k]) => `.wrap-${k}`).join(',\n')},
.wrap-fluid {
  box-sizing: border-box;
  width: 100%;
  margin-inline: auto;
  padding-inline: var(--grid-pad);
}`);

css.push(`.grid,
.flow,
${bps.map(([k]) => `.flow-${k}`).join(',\n')},
.grid-fit {
  display: grid;
  gap: var(--grid-gutter);
  min-width: 0;
}

.grid {
  --grid-span: ${COLUMNS};
  grid-template-columns: repeat(${COLUMNS}, minmax(0, 1fr));
}
.grid > * { grid-column-end: span var(--grid-span); }

.flow { grid-auto-flow: column; grid-auto-columns: minmax(0, 1fr); }
.flow.flow-fit { grid-auto-columns: auto; }

.grid-fit { grid-template-columns: repeat(auto-fit, minmax(min(var(--grid-min), 100%), 1fr)); }`);

const align = [];
for (const v of ['start', 'center', 'end', 'stretch']) {
  align.push(`.items-${v} { align-items: ${v}; }`);
  align.push(`.justify-${v} { justify-items: ${v}; }`);
  align.push(`.self-${v} { align-self: ${v}; }`);
  align.push(`.justify-self-${v} { justify-self: ${v}; }`);
}
for (const v of ['start', 'center', 'end', 'between']) {
  align.push(`.content-${v} { justify-content: ${v === 'between' ? 'space-between' : v}; }`);
}
css.push(align.join('\n'));

css.push(responsive(null).join('\n'));

// After every .gap-* so .gap-3 .gap-x-0 overrides just the column gap.
const gapXY = [];
for (const [k, v] of Object.entries(GAPS)) {
  gapXY.push(`.gap-x-${k} { column-gap: ${v}; }`);
  gapXY.push(`.gap-y-${k} { row-gap: ${v}; }`);
}
css.push(gapXY.join('\n'));

for (const [bp, px] of bps) {
  css.push(`@media (min-width: ${px}px) {\n${indent([...wraps(bp), ...responsive(bp)])}\n}`);
  css.push(`@media (max-width: ${px - 0.02}px) {\n  .hide-${bp}-down { display: none !important; }\n}`);
}

const target = fileURLToPath(new URL('../app/styles/grid.css', import.meta.url));
writeFileSync(target, css.join('\n\n') + '\n');
console.log(`wrote ${target}`);
